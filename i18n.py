def get_translation(lang, key):
    """Get translation for a key in specified language"""
    lang = lang if lang in TRANSLATIONS else "bn"
    return TRANSLATIONS[lang].get(key, TRANSLATIONS["en"].get(key, key))


def get_all_translations(lang="bn"):
    """Get all translations for a language as dict"""
    lang = lang if lang in TRANSLATIONS else "bn"
    return TRANSLATIONS[lang]


def translate_district_name(name, lang="bn"):
    """Translate district name to Bengali if needed"""
    if lang == "bn":
        from data.districts import get_district_by_name
        d = get_district_by_name(name)
        if d:
            return d["bn_name"]
    return name
